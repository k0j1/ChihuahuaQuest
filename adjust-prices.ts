let outLines = [];
let lines = content.split('\n');

for (let line of lines) {
    if (line.includes('value: ') || line.includes('baseVal: ') || line.includes('valueMod: ')) {
        const nameMatchUnique = line.match(/name:\s*"([^"]+)"/);
        if (nameMatchUnique && nameMatchUnique[1] && uniqueVals[nameMatchUnique[1]]) {
            line = line.replace(/value: \d+/, `value: ${uniqueVals[nameMatchUnique[1]]}`);
            line = line.replace(/baseVal: \d+/, `baseVal: ${uniqueVals[nameMatchUnique[1]]}`);
        }
        
        if (nameMatchUnique && nameMatchUnique[1] && baseItemVal[nameMatchUnique[1]]) {
            line = line.replace(/baseVal: \d+/, `baseVal: ${baseItemVal[nameMatchUnique[1]]}`);
        }
        
        const nameMatchPrefix = line.match(/name:\s*"([^"]+)"/);
        if (nameMatchPrefix && nameMatchPrefix[1] && prefixVals[nameMatchPrefix[1]]) {
            let pStr = typeof prefixVals[nameMatchPrefix[1]] === 'number' ? prefixVals[nameMatchPrefix[1]].toFixed(1) : String(prefixVals[nameMatchPrefix[1]]);
            if (pStr.endsWith(".0")) pStr = pStr.substring(0, pStr.length - 2); 
            line = line.replace(/valueMod: [\d\.]+/, `valueMod: ${pStr}`);
        }
    }
    outLines.push(line);
}

fs.writeFileSync('services/geminiService.ts', outLines.join('\n'));
